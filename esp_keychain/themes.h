// themes.h - per-device sprites, LED palettes and text.
//
// To add a theme:
//   1. Make 1+ frames (max 32 px tall, width a multiple of 8 keeps it simple).
//      Convert PNGs with: python3 tools/png2xbm.py my_sprite frame0.png frame1.png
//   2. Paste the arrays below and add a Theme entry to THEMES[].
//   3. Point SELF_THEME_INDEX / PEER_THEME_INDEX in config.h at it.
#pragma once

#include <Arduino.h>

struct Theme {
  const char* name;             // shown on the boot splash
  const uint8_t* const* frames; // XBM frames, U8g2 drawXBMP format
  uint8_t frameCount;
  uint8_t w, h;
  uint16_t frameMs;             // sprite frame time
  uint32_t palette[3];          // 0xRRGGBB: [0] primary, [1] secondary, [2] accent
  const char* closeMessage;     // flashed on the OLED in CLOSE
};

