#!/usr/bin/env python3
"""Convert PNG frames to a U8g2-compatible XBM C array for themes.h.

Usage:
  python3 tools/png2xbm.py NAME frame0.png [frame1.png ...] [--threshold 128] [--invert]

All frames must share the same size (max 32 px tall to fit the 128x32 OLED).
Pixels darker than the threshold become "on" unless --invert is given.
Requires Pillow: pip install pillow
"""
import argparse
import sys

from PIL import Image


def frame_to_xbm(img, threshold, invert):
    img = img.convert("L")
    w, h = img.size
    px = img.load()
    out = []
    for y in range(h):
        for bx in range((w + 7) // 8):
            byte = 0
            for bit in range(8):
                x = bx * 8 + bit
                if x >= w:
                    continue
                on = px[x, y] < threshold
                if invert:
                    on = not on
                if on:
                    byte |= 1 << bit  # XBM is LSB-first
            out.append(byte)
    return w, h, out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("frames", nargs="+")
    ap.add_argument("--threshold", type=int, default=128)
    ap.add_argument("--invert", action="store_true")
    a = ap.parse_args()

    size = None
    print(f"// Generated by tools/png2xbm.py from: {' '.join(a.frames)}")
    for i, path in enumerate(a.frames):
        w, h, data = frame_to_xbm(Image.open(path), a.threshold, a.invert)
        if size and size != (w, h):
            sys.exit(f"{path}: size {w}x{h} differs from first frame {size}")
        size = (w, h)
        print(f"static const uint8_t {a.name}_f{i}[] PROGMEM = {{")
        for j in range(0, len(data), 12):
            print("  " + ", ".join(f"0x{b:02X}" for b in data[j:j + 12]) + ",")
        print("};")
    names = ", ".join(f"{a.name}_f{i}" for i in range(len(a.frames)))
    print(f"static const uint8_t* const {a.name}_frames[] = {{ {names} }};")
    print(f"// width={size[0]} height={size[1]} frames={len(a.frames)}")


if __name__ == "__main__":
    main()
